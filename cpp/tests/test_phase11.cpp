TEST(Bootstrap, CoverageRateNearNominalAndBlocksWidenForClustering){
    //A 90% interval should miss about 10% of the time -> test the rate over many samples, not a single sample.
    //The percentile bootstrap under-covers somewhat in the far tail (about 85% in the Python study), hence the bounds
    Rng rng(6);
    const double z99 = 2.3263478740408408, es_true = distributions::normal::pdf(z99, 0.0, 1.0) / 0.01;
    int cover_v = 0, cover_e = 0;
    for(int s = 0; s < 100; ++s){
        const auto x = distributions::normal::sample(2000, 0.0, 1.0, rng);
        const BootstrapCi ci = bootstrap_var_es(x, 0.99, 300, 1, rng);
        EXPECT_LT(ci.var_lo, ci.var_hi);
        cover_v += (ci.var_lo < z99 && z99 < ci.var_hi) ? 1 : 0;
        cover_e += (ci.es_lo < es_true && es_true < ci.es_hi) ? 1 : 0;
    }
    EXPECT_GE(cover_v, 75); EXPECT_LE(cover_v, 97);
    EXPECT_GE(cover_e, 72); EXPECT_LE(cover_e, 97);
    //clustered volatility: GARCH-like losses
    std::vector<double> g(1500);
    double h = 1e-4;
    const auto z = distributions::normal::sample(1500, 0.0, 1.0, rng);
    for(std::size_t t = 0; t < g.size(); ++t){ g[t] = std::sqrt(h) * z[t]; h = 1e-6 + 0.10 * g[t] * g[t] + 0.89 * h; }
    Rng r1(9), r2(9);
    const BootstrapCi iid = bootstrap_var_es(g, 0.99, 800, 1, r1);
    const BootstrapCi blk = bootstrap_var_es(g, 0.99, 800, 25, r2);
    EXPECT_GT(blk.var_hi - blk.var_lo, iid.var_hi - iid.var_lo);
    EXPECT_THROW(bootstrap_var_es(std::vector<double>(10, 1.0), 0.99, 100, 1, rng), InvalidInputError);
}

TEST(ConditionalEvt, BacktestNoLookAhead){
    Rng rng(5);
    const auto z = distributions::normal::sample(400, 0.0, 0.01, rng);
    PriceMatrix p(201, 2);
    p.row(0).setConstant(100.0);
    for(Eigen::Index t = 0; t < 200; ++t)
        for(Eigen::Index c = 0; c < 2; ++c) p(t + 1, c) = p(t, c) * (1.0 + z[static_cast<std::size_t>(2 * t + c)]);
    PriceMatrix future = p;
    for(Eigen::Index r = 181; r < future.rows(); ++r) future.row(r) *= 0.5 + 2.5 * static_cast<double>(r - 181) / static_cast<double>(future.rows() - 181);
    WeightVector w(2); w << 0.6, 0.4;
    const auto a = rolling_backtest(p, w, 150, 0.99, BacktestMethod::GarchEvt);
    const auto b = rolling_backtest(future, w, 150, 0.99, BacktestMethod::GarchEvt);
    for(std::size_t k = 0; k <= 181 - 151; ++k) EXPECT_EQ(a.var[k], b.var[k]);
}
